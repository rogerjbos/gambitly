#!/usr/bin/env python3
"""Convert the simple cburnett piece SVGs into Android vector drawables.

Handles only what those files use: nested <g> with inherited presentation
attributes, <path> and <circle>.

Usage: svg_to_vector.py <svg_dir> <res_drawable_dir>
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG_NS = "{http://www.w3.org/2000/svg}"
INHERITED = ("fill", "fill-rule", "stroke", "stroke-linecap", "stroke-linejoin", "stroke-width")
NAMES = {"K": "king", "Q": "queen", "R": "rook", "B": "bishop", "N": "knight", "P": "pawn"}


def colour(value):
    """SVG colour -> Android #RRGGBB, or None for 'none'."""
    if value is None or value == "none":
        return None
    if value.startswith("#") and len(value) == 4:
        return "#" + "".join(c * 2 for c in value[1:]).upper()
    if value.startswith("#") and len(value) == 7:
        return value.upper()
    raise ValueError(f"unsupported colour {value!r}")


def circle_path(cx, cy, r):
    return (f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z")


def walk(node, style, out):
    style = dict(style)
    for key in INHERITED:
        if key in node.attrib:
            style[key] = node.attrib[key]
    tag = node.tag.replace(SVG_NS, "")
    if tag in ("svg", "g"):
        for child in node:
            walk(child, style, out)
        return
    if tag == "path":
        data = node.attrib["d"]
    elif tag == "circle":
        data = circle_path(float(node.attrib["cx"]), float(node.attrib["cy"]), float(node.attrib["r"]))
    else:
        raise ValueError(f"unsupported element <{tag}>")

    attrs = [f'android:pathData="{data}"']
    fill = colour(style.get("fill", "#000"))  # SVG default fill is black
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
        if style.get("fill-rule") == "evenodd":
            attrs.append('android:fillType="evenOdd"')
    stroke = colour(style.get("stroke"))
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
        attrs.append(f'android:strokeWidth="{style.get("stroke-width", "1")}"')
        attrs.append(f'android:strokeLineCap="{style.get("stroke-linecap", "butt")}"')
        attrs.append(f'android:strokeLineJoin="{style.get("stroke-linejoin", "miter")}"')
    out.append("    <path\n        " + "\n        ".join(attrs) + " />")


def convert(svg_path: Path) -> str:
    root = ET.parse(svg_path).getroot()
    if root.attrib.get("viewBox") != "0 0 45 45":
        raise ValueError(f"{svg_path}: unexpected viewBox")
    paths = []
    walk(root, {}, paths)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/svg_to_vector.py from the cburnett piece set"
        " (Colin M.L. Burnett, GPLv2+). Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="45dp"\n    android:height="45dp"\n'
        '    android:viewportWidth="45"\n    android:viewportHeight="45">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    dst.mkdir(parents=True, exist_ok=True)
    for svg in sorted(src.glob("*.svg")):
        side = "white" if svg.stem[0] == "w" else "black"
        name = f"piece_{side}_{NAMES[svg.stem[1]]}.xml"
        (dst / name).write_text(convert(svg))
        print(name)


if __name__ == "__main__":
    main()
